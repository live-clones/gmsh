static IntPt *GQTet[10] = {tetP1, tetP1, tetP2, tetP3, tetP4,
                           tetP5, tetP6, tetP7, tetP8, tetP9};
static int GQTetnPt[10] = {1, 1, 4, 5, 11, 14, 24, 31, 43, 53};

// The Grundmann-Moller rule of degree 2s + 1 (SIAM J. Numer. Anal. 15, 1978):
// for i = 0, ..., s, the points of barycentric coordinates (2 b_j + 1) / (d + 3
// - 2 i) for all b_0 + b_1 + b_2 + b_3 = s - i, of weight (-1)^i 2^-2s (d + 3 -
// 2 i)^d / (i! (d + 3 - i)!), with d = 2s + 1. Its weights alternate in sign,
// which makes it lose a few digits at high degrees.
static void grundmannMoller(int s, std::vector<IntPt> &pts)
{
  const int d = 2 * s + 1;
  for(int i = 0; i <= s; i++) {
    double den = d + 3 - 2 * i, w = std::pow(den, d) / std::pow(2., 2 * s);
    for(int k = 2; k <= i; k++) w /= k;
    for(int k = 2; k <= d + 3 - i; k++) w /= k;
    if(i % 2) w = -w;
    const int k = s - i;
    for(int b0 = 0; b0 <= k; b0++) {
      for(int b1 = 0; b1 <= k - b0; b1++) {
        for(int b2 = 0; b2 <= k - b0 - b1; b2++) {
          int b3 = k - b0 - b1 - b2;
          IntPt p;
          p.pt[0] = (2 * b1 + 1) / den;
          p.pt[1] = (2 * b2 + 1) / den;
          p.pt[2] = (2 * b3 + 1) / den;
          p.weight = w;
          pts.push_back(p);
        }
      }
    }
  }
}

// The rules of order 10 to 21 are Grundmann-Moller rules, those of higher
// orders (or of any order if forceTensorRule is set) collapsed tensor products
// of Gauss-Legendre rules, both computed once
static const std::vector<IntPt> &computedRule(int order, bool tensor)
{
  // the number of Gauss points per direction, or s: several orders share a
  // rule
  const int n = tensor ? (order + 4) / 2 : order / 2;
  static std::map<std::pair<int, bool>, std::vector<IntPt>> rules;
  static std::mutex mutex;
  std::lock_guard<std::mutex> lock(mutex);
  std::vector<IntPt> &pts = rules[{n, tensor}];
  if(pts.empty()) {
    if(tensor) {
      pts.resize(n * n * n);
      GaussLegendreTet(n, n, n, pts.data());
    }
    else
      grundmannMoller(n, pts);
  }
  return pts;
}

IntPt *getGQTetPts(int order, bool forceTensorRule)
{
  if(!forceTensorRule && order < 10) return GQTet[order];
  return const_cast<IntPt *>(
    computedRule(order, forceTensorRule || order > 21).data());
}

int getNGQTetPts(int order, bool forceTensorRule)
{
  if(!forceTensorRule && order < 10) return GQTetnPt[order];
  if(forceTensorRule || order > 21) {
    int n = (order + 4) / 2;
    return n * n * n;
  }
  int s = order / 2, n = 0;
  for(int k = 0; k <= s; k++) n += (k + 1) * (k + 2) * (k + 3) / 6;
  return n;
}
