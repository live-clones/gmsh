static int GQTnPt[21] = {1,  1,  3,  4,  6,  7,  12, 13, 16, 19, 25,
                         27, 33, 37, 42, 48, 52, 61, 70, 73, 79};

// The collapsed tensor products of Gauss-Legendre rules, for the orders above
// 20 (or any order if forceTensorRule is set), computed once
static const std::vector<IntPt> &tensorRule(int order)
{
  // by the number of Gauss points per direction: several orders share a rule
  const int n = (order + 3) / 2;
  static std::map<int, std::vector<IntPt>> rules;
  static std::mutex mutex;
  std::lock_guard<std::mutex> lock(mutex);
  std::vector<IntPt> &pts = rules[n];
  if(pts.empty()) {
    pts.resize(n * n);
    GaussLegendreTri(n, n, pts.data());
  }
  return pts;
}

IntPt *getGQTPts(int order, bool forceTensorRule)
{
  if(!forceTensorRule && order < 21) return GQT[order];
  return const_cast<IntPt *>(tensorRule(order).data());
}

int getNGQTPts(int order, bool forceTensorRule)
{
  if(!forceTensorRule && order < 21) return GQTnPt[order];
  return ((order + 3) / 2) * ((order + 3) / 2);
}
